// F07: uninstall removes the ignore lines it appended and leaves an
// identical rule the consumer already had.
func TestUninstall_PreexistingGitignoreRule_Survives(t *testing.T) {
	root := tempRepo(t, true)
	pf(t, root, gitignoreTarget, "keep/\n/"+zharnessDir+"/\n")
	mustInstall(t, root)

	if got := loadOwnership(root).get(kindGitignore, "/"+zharnessDir+"/"); got != originPreexisting {
		t.Fatalf("consumer ignore rule recorded as %q, want %q", got, originPreexisting)
	}

	var sb strings.Builder
	if err := Uninstall(root, &sb); err != nil {
		t.Fatalf("uninstall: %v", err)
	}
	got := rf(t, root, gitignoreTarget)
	if !containsLine(got, "/"+zharnessDir+"/") {
		t.Errorf("consumer-owned ignore rule removed by uninstall:\n%s", got)
	}
	if !containsLine(got, "keep/") {
		t.Errorf("unrelated ignore rule removed by uninstall:\n%s", got)
	}
	if containsLine(got, gitignoreMarker) {
		t.Errorf("installer-added marker survived uninstall:\n%s", got)
	}
}

