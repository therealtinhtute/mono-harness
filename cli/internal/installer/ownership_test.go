// F01: creating AGENTS.md does not confer ownership of every byte written
// into it later. Uninstall must strip the block and keep the prose.
func TestUninstall_AgentsCreatedByInstall_ConsumerProsePreserved(t *testing.T) {
	root := tempRepo(t, true)
	mustInstall(t, root)

	prose := "\n## Deployment\n\nAll deploys require a second approver.\n"
	before := rf(t, root, agentsTarget)
	pf(t, root, agentsTarget, before+prose)

	var sb strings.Builder
	if err := Uninstall(root, &sb); err != nil {
		t.Fatalf("uninstall: %v", err)
	}

	got, err := os.ReadFile(filepath.Join(root, agentsTarget))
	if err != nil {
		t.Fatalf("consumer prose lost: AGENTS.md was deleted (%v)\n%s", err, sb.String())
	}
	if !strings.Contains(string(got), "second approver") {
		t.Errorf("consumer prose missing after uninstall:\n%s", got)
	}
	if strings.Contains(string(got), blockBegin) || strings.Contains(string(got), blockEnd) {
		t.Errorf("managed block survived uninstall:\n%s", got)
	}
}

