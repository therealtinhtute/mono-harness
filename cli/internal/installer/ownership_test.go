// Found by the 2026-09-08 full check. The ledger used to be saved only after
// the write loop, so an install that failed midway left managed files on disk
// with no record of who made them. Blocking the first target's directory makes
// Install fail for real; the ledger must already be on disk when it does.
func TestInstall_FailsMidway_LedgerIsAlreadyOnDisk(t *testing.T) {
	root := tempRepo(t, true)
	withSource(t, map[string]string{"WORKFLOW.md": wfUp1})
	// `docs` as a regular file makes MkdirAll for docs/WORKFLOW.md fail.
	if err := os.WriteFile(filepath.Join(root, "docs"), []byte("not a directory\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	var sb strings.Builder
	if err := Install(root, "t", &sb); err == nil {
		t.Fatalf("install reported success with docs/ blocked\n%s", sb.String())
	}
	own := loadOwnership(root)
	if got := own.get(kindFile, workflowTarget); got != originCreated {
		t.Fatalf("a failed install left %s recorded as %q; the ledger must be written before the first managed file", workflowTarget, got)
	}
}

// The state a genuinely interrupted install leaves: the ledger is on disk
// (it is written first) but the base manifest and originals are not (they are
// written last). The retry must read the record rather than re-deriving
// provenance from the files the first attempt already wrote.
func TestInstall_InterruptedThenRetried_DoesNotRelabelGeneratedFiles(t *testing.T) {
	root := tempRepo(t, true)
	withSource(t, map[string]string{"WORKFLOW.md": wfUp1})
	mustInstall(t, root)

	if err := os.Remove(filepath.Join(root, manifestFile)); err != nil {
		t.Fatal(err)
	}
	if err := os.RemoveAll(filepath.Join(root, originalDir)); err != nil {
		t.Fatal(err)
	}

	mustInstall(t, root)

	if p, ok := findOriginal(root, workflowTarget); ok {
		b, _ := os.ReadFile(p)
		t.Fatalf("retry after an interrupted install captured generated bytes as a pre-install original at %s:\n%s", p, b)
	}
	if got := loadOwnership(root).get(kindFile, workflowTarget); got != originCreated {
		t.Fatalf("retry recorded %s as %q, want %q", workflowTarget, got, originCreated)
	}

	var sb strings.Builder
	if err := Uninstall(root, &sb); err != nil {
		t.Fatalf("uninstall: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, workflowTarget)); !os.IsNotExist(err) {
		t.Errorf("uninstall left a file zharness created behind\n%s", sb.String())
	}
}

// The ledger is append-only per key: the first decision is the durable one.
